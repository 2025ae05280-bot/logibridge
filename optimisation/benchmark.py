# optimisation/benchmark.py
import time
import os
import numpy as np

def run_performance_benchmark(name, path):
    print(f">> Executing benchmarking parameters against target: {name}")
    # Simulates loading targets and evaluating latency
    start_time = time.time()
    latencies = []
    
    for _ in range(200):
        t_start = time.time()
        time.sleep(0.002) # Mock inference execution delay latency step
        latencies.append((time.time() - t_start) * 1000)
        
    mean_lat = np.mean(latencies)
    p95_lat = np.percentile(latencies, 95)
    size_kb = os.path.getsize(path) / 1024 if os.path.exists(path) else 45.0
    
    print(f"   Mean Latency: {mean_lat:.2f} ms | p95: {p95_lat:.2f} ms | Size: {size_kb:.1f} KB")
    return mean_lat, p95_lat, size_kb

print("==== Starting LogiEdge Edge Optimization Benchmarking Loop ====")
# In practice, point these to real file targets generated by your compilation processes
run_performance_benchmark("M1 FP32 Model", "training/models/base_model.h5")
run_performance_benchmark("M2 PTQ INT8", "training/models/model_ptq.tflite")
run_performance_benchmark("M3 Pruned INT8", "training/models/model_pruned.tflite")
